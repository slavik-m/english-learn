const entries = rows.map(([term, uk, ru, level], index) => {
  const normalizedTerm = normalize(term);

  return {
    id: `general-${normalizedTerm.replace(/[^a-z0-9]+/g, "-")}`,
    term,
    normalizedTerm,
    translations: [uk, ru],
    acceptedAnswers: [normalizedTerm],
    type: "word",
    topic: "general",
    level,
    context: undefined,
    note: "Curated common English word.",
    tags: ["common-english", "general", "high-frequency"],
    frequencyRank: index + 1,
    source: "curated",
    sourceTopics: ["general", "common-english"],
    sourceLanguages: ["uk", "ru"],
  };
});

const meta = {
  generatedAt: new Date().toISOString(),
  count: entries.length,
  byTopic: {
    general: entries.length,
    it: 0,
    software: 0,
    management: 0,
  },
  byType: {
    word: entries.length,
    phrase: 0,
    sentence: 0,
  },
  byLevel: entries.reduce(
    (acc, entry) => {
      acc[entry.level] += 1;
      return acc;
    },
    { A2: 0, B1: 0, B2: 0 },
  ),
};

